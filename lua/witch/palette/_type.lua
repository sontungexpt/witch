--- A color accepted by this module:
--- - `string`: a Neovim color name (e.g. `"Red"`), `#rgb`, `#rrggbb`, or `#rrggbbaa` (alpha ignored).
--- - `integer`: a 24-bit RGB value (e.g. `0xff8800`).
--- @alias witch.Color string|integer
---
--- @class witch.Palette
---
